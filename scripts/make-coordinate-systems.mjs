// Generates src/lib/coordinateSystems.js from the authoritative EPSG dataset
// (epsg-index) so every coordinate-system option carries the correct EPSG code
// — no hand-typed codes. Includes all NAD83 + NAD27 projected systems (State
// Plane in ftUS/ft/meters, UTM zones, and statewide projections) plus WGS84
// lat/long.
//
// Run: node scripts/make-coordinate-systems.mjs
import { createRequire } from "module";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const require = createRequire(import.meta.url);
const all = require("epsg-index/all.json");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const isMeters = (unit) => /met(re|er)/i.test(String(unit || ""));

const entries = [];
for (const key of Object.keys(all)) {
  const e = all[key];
  const name = e.name || "";
  if (!(name.startsWith("NAD83 / ") || name.startsWith("NAD27 / "))) continue;

  // The meters variants have no unit suffix in the EPSG name (the ftUS/ft ones
  // do), so spell meters out — that ambiguity is exactly what mislocates points.
  const label = isMeters(e.unit) && !/\(ft/i.test(name) ? `${name} (m)` : name;

  const datum = name.startsWith("NAD83") ? "nad83" : "nad27";
  const isUtm = /UTM zone/i.test(name);
  const group = isUtm ? `${datum}utm` : datum;

  entries.push({ epsg: Number(e.code), name: label, group });
}

entries.sort((a, b) => a.name.localeCompare(b.name));

const systems = [
  { epsg: 4326, name: "WGS 84 — latitude / longitude (GPS)", group: "latlon" },
  ...entries,
];

const out = path.join(root, "src/lib/coordinateSystems.js");
const header =
  "// AUTO-GENERATED by scripts/make-coordinate-systems.mjs — do not edit by hand.\n" +
  `// ${systems.length} coordinate systems from the EPSG dataset (epsg-index).\n` +
  "// Each entry's epsg is the authoritative code; selecting a system sets it.\n\n";

const body =
  "export const COORDINATE_SYSTEMS = [\n" +
  systems
    .map((s) => `  { epsg: ${s.epsg}, name: ${JSON.stringify(s.name)}, group: ${JSON.stringify(s.group)} },`)
    .join("\n") +
  "\n];\n\n" +
  `export const COORDINATE_SYSTEM_GROUPS = [
  { key: "latlon", label: "Latitude / Longitude (GPS)" },
  { key: "nad83", label: "NAD83 — State Plane & projections" },
  { key: "nad83utm", label: "NAD83 — UTM zones" },
  { key: "nad27", label: "NAD27 (legacy) — State Plane & projections" },
  { key: "nad27utm", label: "NAD27 (legacy) — UTM zones" },
];

export const COORDINATE_SYSTEM_BY_EPSG = new Map(
  COORDINATE_SYSTEMS.map((s) => [String(s.epsg), s]),
);
`;

fs.writeFileSync(out, header + body, "utf8");
console.log(`Wrote ${systems.length} systems to ${out}`);
